# Members inherited from sklearn / torch reference their own doc trees, which
# do not resolve here. Returns `None` rather than `skip` for a non-match:
# autosummary hard-codes `skip=False`, so returning it would force-include
# otherwise-private members.
def _skip_inherited(app, what, name, obj, skip, options):
  mod = getattr(obj, "__module__", "")
  if isinstance(mod, str) and (
    mod.startswith("sklearn") or mod.startswith("torch")
  ):
    return True
  return None


