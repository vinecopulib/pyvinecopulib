def process_cross_references(content: str, is_docstring: bool = True) -> str:
  classes = list(_CLASS_MODULE)
  modules = [
    "pyvinecopulib.core",
    "pyvinecopulib.families",
    "pyvinecopulib.utils",
    "pyvinecopulib.margins",
    "pyvinecopulib.sklearn",
    "pyvinecopulib.sklearn.backends",
    "pyvinecopulib.torch",
  ]

  meth_ref = r":meth:`" if is_docstring else r"{py:meth}`"
  cls_ref = r":class:`" if is_docstring else r"{py:class}`"
  mod_ref = r":mod:`" if is_docstring else r"{py:mod}`"
  func_ref = r":func:`" if is_docstring else r"{py:func}`"

  # Docstrings (RST) use double backticks; markdown sources use single.
  bt = "``" if is_docstring else "`"

  def _fqn(cls: str) -> str:
    return f"{_CLASS_MODULE[cls]}.{cls}"

  # Longest class name first so e.g. ``FitControlsTorchVinecop`` wins over
  # ``FitControlsVinecop`` and ``BicopBase`` over ``Bicop`` in the alternation.
  class_alt = "|".join(
    re.escape(c) for c in sorted(classes, key=len, reverse=True)
  )
  # ``Class.method()`` -> :meth:`~pkg.mod.Class.method`
  content = re.sub(
    rf"{bt}({class_alt})\.(\w+)\(\){bt}",
    lambda m: f"{meth_ref}~{_fqn(m.group(1))}.{m.group(2)}`",
    content,
  )
  # ``Class.attr`` -> :class:`~pkg.mod.Class.attr`
  content = re.sub(
    rf"{bt}({class_alt})\.(\w+){bt}",
    lambda m: f"{cls_ref}~{_fqn(m.group(1))}.{m.group(2)}`",
    content,
  )
  # ``Class()`` -> :class:`~pkg.mod.Class`, the constructor-call spelling.
  # Written before the bare form, which would otherwise leave the parentheses
  # outside the role and render them as literal text.
  content = re.sub(
    rf"{bt}({class_alt})\(\){bt}",
    lambda m: f"{cls_ref}~{_fqn(m.group(1))}`",
    content,
  )
  # bare ``Class`` -> :class:`~pkg.mod.Class`
  for cls in classes:
    content = re.sub(
      rf"{bt}{re.escape(cls)}{bt}", f"{cls_ref}~{_fqn(cls)}`", content
    )
  # bare ``function`` -> :func:`~pkg.mod.function`
  for func, mod in _FUNCTION_MODULE.items():
    content = re.sub(
      rf"{bt}{re.escape(func)}{bt}", f"{func_ref}~{mod}.{func}`", content
    )
  # Module references — longest-prefix first so `pyvinecopulib.sklearn.backends`
  # wins over `pyvinecopulib.sklearn`.
  for mod in sorted(modules, key=len, reverse=True):
    content = re.sub(rf"{bt}{re.escape(mod)}{bt}", rf"{mod_ref}{mod}`", content)

  return content


def autodoc_process_docstring(app, what, name, obj, options, lines):
  docstring = process_cross_references("\n".join(lines))
  lines.clear()
  lines.extend(docstring.splitlines())


_NB_ARRAY_RE = re.compile(r"numpy\.ndarray\[[^\]]*\]")


def autodoc_process_signature(
  app, what, name, obj, options, signature, return_annotation
):
  # nanobind embeds array parameters in the signature as
  # ``numpy.ndarray[dtype=..., shape=..., order=...]`` (a form intersphinx
  # can't resolve). Collapse to the resolvable ``numpy.ndarray``; the precise
  # shape / dtype is documented in the numpydoc Parameters/Returns type strings.
  def _fix(s):
    return _NB_ARRAY_RE.sub("numpy.ndarray", s) if s else s

  return _fix(signature), _fix(return_annotation)


